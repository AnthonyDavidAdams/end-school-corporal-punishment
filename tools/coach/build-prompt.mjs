// Assembles the Behavior Coach's system prompt from the charter, the training modules and the evidence
// file, and writes it as a PHP include so the web server never serves it raw.
//   node tools/coach/build-prompt.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const r = (p) => readFileSync(join(root, p), "utf8");

const charter = r("data/coach/charter.md");
const modules = ["02-classroom-routines", "03-office-response-ladder", "04-repair-conversations", "05-repeated-referrals", "06-disabilities-and-trauma", "07-parents"]
  .map((m) => r(`training/modules/${m}.md`).replace(/\(`[^`]*`[^)]*\)/g, "").replace(/`\.\.\/[^`]*`/g, "the evidence file"));
const ev = r("training/evidence.md");
const slice = (from, to) => { const a = ev.indexOf(from), b = to ? ev.indexOf(to) : ev.length; return ev.slice(a, b).trim(); };
const evidence = [slice("### A1.", "### A2."), slice("### A13.", "## Part B"), slice("## Part B", null)].join("\n\n");

const prompt = [charter,
  "# The training modules (what the Safe Discipline Program teaches schools; quote the scripts freely)", ...modules,
  "# The evidence file (the only source of numbers you may use)", evidence,
  "Reminder: never ask for or repeat a name; at most two questions before a plan; one number per reply at most; under 250 words unless asked for a full plan; no em dashes; end with one question or one next step."].join("\n\n");
if (/^ESCPPROMPT;?$/m.test(prompt)) throw new Error("heredoc terminator inside prompt");
writeFileSync(join(root, "site/coach/prompt.inc.php"), `<?php\n// Generated by tools/coach/build-prompt.mjs. Do not edit here.\n$COACH_PROMPT = <<<'ESCPPROMPT'\n${prompt}\nESCPPROMPT;\n`);
console.log(`prompt: ${prompt.split(/\s+/).length} words`);
